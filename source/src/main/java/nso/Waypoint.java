package nso;

public final class Waypoint {

    public short minX;

    public short minY;

    public short maxX;

    public short maxY;

    public Waypoint(short minX1, short minY2, short maxX3, short maxY4) {
        this.minX = minX1;
        this.minY = minY2;
        this.maxX = maxX3;
        this.maxY = maxY4;
    }
}
